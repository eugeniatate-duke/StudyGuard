#!/usr/bin/env node
/**
 * eval/redteam.js - red-team stress test (adversarial and edge cases)
 *
 *     node eval/redteam.js
 *     node eval/redteam.js --out docs/redteam-results.md
 *
 * Reads eval/redteam.csv: attacks and edge cases, each with the
 * outcome a sensible tool SHOULD give ("expected" HOLD or PASS), by design.
 * Runs rules v1, rules v2 and the two trained models, then reports per category:
 *
 *   HOLD-expected categories: how many were held (higher = harder to evade)
 *   PASS-expected category (terse_legitimate): how many were wrongly held
 *
 * IMPORTANT HONESTY NOTE: these cases were written by the AI assistant that also
 * helped build the rules, and are NOT a fair measure of general accuracy.
 * They map where the tool is weak. They were not used to tune any rule.
 */
const fs = require("fs");
const path = require("path");
const { parseCsv } = require("./csv.js");
const Engine = require("../engine.js");
const Model = require("../model.js");

const root = path.join(__dirname, "..");
const outFlag = process.argv.indexOf("--out");
const outPath = outFlag > -1 ? process.argv[outFlag + 1] : null;

const rows = parseCsv(fs.readFileSync(path.join(__dirname, "redteam.csv"), "utf8"));

function loadModel(file) {
  const p = path.join(root, "model", file);
  return fs.existsSync(p) ? Model.createAnalyzer(JSON.parse(fs.readFileSync(p, "utf8"))) : null;
}
const systems = [
  ["Rules v1", (p, a) => Engine.analyzePrompt(p, { attempt: a, ruleSet: "v1" })],
  ["Rules v2", (p, a) => Engine.analyzePrompt(p, { attempt: a, ruleSet: "v2" })],
  ["Model (JS-trained)", loadModel("model.json") && ((p, a) => loadModel("model.json")(p, { attempt: a }))],
  ["Model (scikit-learn)", loadModel("model.sklearn.json") && ((p, a) => loadModel("model.sklearn.json")(p, { attempt: a }))],
].filter(([, fn]) => fn);

const held = (fn, r) => fn(r.prompt, r.attempt || "").decision === "needs_effort";
const categories = [...new Set(rows.map((r) => r.category))];
const pct = (k, n) => (n ? Math.round((100 * k) / n) + "%" : "n/a");

const lines = [
  "# Red-team results", "",
  "Generated by `node eval/redteam.js`. Cases are in `eval/redteam.csv`.", "",
  "**Read this first:** the cases were written by the AI assistant that also helped build the rules, and the",
  '"expected" outcome is the assistant\'s judgement. This is a stress test that maps weaknesses, **not** a measure',
  "of general accuracy. No rule was tuned on these cases.", "",
  "For categories that should be HELD the number is the share held (higher is better). For `terse_legitimate`",
  "(honest prompts that should PASS) the number is the share wrongly held (lower is better).", "",
  "| Category | Cases | " + systems.map(([n]) => n).join(" | ") + " |",
  "|---|---|" + systems.map(() => "---").join("|") + "|",
];
for (const cat of categories) {
  const sub = rows.filter((r) => r.category === cat);
  const cells = systems.map(([, fn]) => {
    const k = sub.filter((r) => held(fn, r)).length;
    return `${k}/${sub.length} (${pct(k, sub.length)})`;
  });
  const label = cat === "terse_legitimate" ? `${cat} (wrongly held)` : `${cat} (held)`;
  lines.push(`| ${label} | ${sub.length} | ${cells.join(" | ")} |`);
}

const v2 = systems.find(([n]) => n === "Rules v2")[1];
const evaded = rows.filter((r) => r.expected === "HOLD" && !held(v2, r));
const wrong = rows.filter((r) => r.expected === "PASS" && held(v2, r));
lines.push("", "## Cases rules v2 let through (should have been held)", "");
lines.push(evaded.length ? "| id | category | prompt | attempt |" : "_None._", evaded.length ? "|---|---|---|---|" : "");
evaded.forEach((r) => lines.push(`| ${r.id} | ${r.category} | ${r.prompt.replace(/\|/g, "\\|")} | ${(r.attempt || "").replace(/\|/g, "\\|")} |`));
lines.push("", "## Honest prompts rules v2 wrongly held", "");
lines.push(wrong.length ? "| id | prompt |" : "_None._", wrong.length ? "|---|---|" : "");
wrong.forEach((r) => lines.push(`| ${r.id} | ${r.prompt.replace(/\|/g, "\\|")} |`));

lines.push("", "## What this shows", "",
  "- Wording-based rules are strongest on plain request phrasing and weakest on indirection, role-play,",
  "  other languages and look-alike characters.",
  "- Filler in the attempt box earns no credit when it repeats the same few words, but varied nonsense text",
  "  still counts as an attempt: the tool cannot tell sincere effort from padding.",
  "- Following the full hint plan literally (a one-line stuck point plus the example attempt) unlocks a request",
  "  that still contains no real thinking, while a single content-free sentence alone does not. The hints ask",
  "  for real content, but nothing enforces it.",
  "- Rules are precise but narrow; the trained models catch more evasions but wrongly hold many short, honest",
  "  prompts (terse_legitimate), because they hold anything that lacks effort words.",
  "- None of this is stopped by a determined student, who can simply type into the chatbot directly. The",
  "  tool is a coaching nudge, never an enforcement mechanism.", "");

const md = lines.join("\n");
console.log(md);
if (outPath) { fs.writeFileSync(outPath, md); console.log("\nWritten to", outPath); }
