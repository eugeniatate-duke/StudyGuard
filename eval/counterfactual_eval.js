#!/usr/bin/env node
/**
 * eval/counterfactual_eval.js - are the hints valid and minimal?
 *
 *     node eval/counterfactual_eval.js
 *     node eval/counterfactual_eval.js --out docs/counterfactual-results.md
 *
 * For every dev and held-out prompt that rules v2 holds, ask counterfactual.js
 * for its advice and check:
 *   VALIDITY     adding the suggested content (re-scored by the real engine)
 *                reaches the pass line.
 *   MINIMALITY   removing any one suggested step drops the prompt back below
 *                the pass line (every step is needed).
 *   SIZE         how many steps the student is asked to take.
 * Labels are not used. Validity here is measured against the rule engine
 * itself, not against a student's understanding.
 */
const fs = require("fs");
const path = require("path");
const { parseCsv } = require("./csv.js");
const Engine = require("../engine.js");
const Counterfactual = require("../counterfactual.js");

const outFlag = process.argv.indexOf("--out");
const outPath = outFlag > -1 ? process.argv[outFlag + 1] : null;
const read = (f) => parseCsv(fs.readFileSync(path.join(__dirname, f), "utf8"));
const rows = [...read("prompts.csv"), ...read("heldout.csv")].filter((r) => r.prompt && r.prompt.trim());

// Rebuild the text that a student following a subset of the steps would produce.
function withSteps(prompt, attempt, steps) {
  let p = prompt, a = attempt;
  for (const s of steps) {
    const sug = Counterfactual.SUGGESTIONS.find((x) => x.id === s.id);
    if (sug.where === "attempt") a = (a + " " + sug.example).trim();
    else p = p + " " + sug.example;
  }
  return Engine.analyzePrompt(p, { attempt: a });
}

let held = 0, valid = 0, minimal = 0, rewordable = 0;
const sizes = [], failures = [];
for (const r of rows) {
  const attempt = r.attempt || "";
  const base = Engine.analyzePrompt(r.prompt, { attempt });
  if (base.decision !== "needs_effort") continue;
  held++;
  const hint = Counterfactual.generateHint(r.prompt, { attempt });
  if (hint.reword) rewordable++;
  if (hint.verified) valid++; else failures.push(r);
  sizes.push(hint.steps.length);
  const needed = hint.steps.every((_, i) => {
    const rest = hint.steps.filter((__, j) => j !== i);
    return rest.length === 0 || withSteps(r.prompt, attempt, rest).score < base.threshold;
  });
  if (hint.verified && needed) minimal++;
}
const pct = (k, n) => `${k}/${n} (${Math.round((100 * k) / n)}%)`;
const avg = (a) => (a.reduce((x, y) => x + y, 0) / a.length).toFixed(2);
const dist = {};
sizes.forEach((s) => (dist[s] = (dist[s] || 0) + 1));

const md = [
  "# Counterfactual hint evaluation", "",
  "Generated by `node eval/counterfactual_eval.js`. No labels used.", "",
  `Prompts held by rules v2 (dev + held-out): ${held}.`, "",
  "| Property | Result |", "|---|---|",
  `| **Valid**: following the advice reaches the pass line | ${pct(valid, held)} |`,
  `| **Minimal**: valid, and every step is necessary | ${pct(minimal, held)} |`,
  `| Average steps asked of the student | ${avg(sizes)} |`,
  `| Step-count distribution | ${Object.entries(dist).map(([k, v]) => `${k} step(s): ${v}`).join(", ")} |`,
  `| Also offered a "reword" option (removing a trigger word alone would pass) | ${pct(rewordable, held)} |`, "",
  failures.length ? "## Prompts where the advice does not reach the pass line\n\n" + failures.map((r) => `- ${r.id}: ${r.prompt}`).join("\n") + "\n" : "No prompt was left without a valid plan.", "",
  "## Limits", "",
  "- Validity is measured against the rule engine, which also produced the hints; it shows the advice is consistent with the scorer, not that it helps a student.",
  "- The checks use the example sentences from `counterfactual.js`. Any content matching the same patterns would unlock the prompt, including content with no real thinking (see `docs/redteam-results.md`).",
  "- Actionability (can a student do this in a minute? is it real learning behaviour?) was not rated by people; no user study was run.", "",
].join("\n");
console.log(md);
if (outPath) { fs.writeFileSync(outPath, md); console.log("Written to", outPath); }
