/**
 * journalexport.js - StudyGuard "XAI Learning Journal" report builder (Step 8)
 *
 * WHAT THIS FILE DOES
 * Turns the saved journal entries (journal.js) into a readable report that a
 * student can hand in with homework. Two steps:
 *
 *   buildReport(entries, options)  ->  a structured report object
 *   toMarkdown(report, options)    ->  the same report as Markdown text
 *
 * The journal page (journalpage.js) draws the same report object on screen, so
 * the screen, the Markdown file and the printed PDF always say the same thing.
 *
 * WHAT THE REPORT CONTAINS
 * - A summary (submits, holds, "send anyway" choices, recoveries)
 * - Sessions (entries more than 30 minutes apart start a new session)
 * - For each step: what was asked, how StudyGuard read it and why, the words
 *   that pushed the score, the advice shown, the student's attempt, and what
 *   happened next (the trial-and-error path)
 * - Reflection questions for the student to answer
 *
 * HONESTY
 * The report states that scores are rule points, not probabilities, and that
 * it was generated from the student's own saved log.
 *
 * No DOM code, so it runs in Chrome and in Node tests.
 */
(function () {
  const DEFAULT_GAP_MINUTES = 30;

  const REFLECTION_PROMPTS = [
    "What did StudyGuard's explanation help me notice about how I ask for help?",
    "Which of my own ideas did I add, and did they change the answer I got?",
    'When I chose "Send anyway", why did I decide that? Was it the right call?',
    "What will I try on my own first next time?",
  ];

  const CAVEAT =
    "This journal was generated by StudyGuard from my own saved log. Scores " +
    "are rule points from a transparent scorer, not probabilities or a " +
    "judgment of me, and the scorer can be wrong.";

  const hasScore = (n) => typeof n === "number" && Number.isFinite(n);

  /** "15 -> 52", "15", or "unknown" depending on what is known. */
  function scoreChange(from, to) {
    if (hasScore(from) && hasScore(to)) return from + " \u2192 " + to;
    if (hasScore(to)) return String(to);
    if (hasScore(from)) return String(from);
    return "unknown";
  }

  /** Plain-English description of what happened after (or at) a step. */
  function describeOutcome(step, next) {
    if (step.action === "passed") return "Sent normally.";
    if (step.action === "sent_anyway") return "Chose to send despite the hold.";
    // held
    if (!next) return "No further step was recorded after this hold.";
    if (next.action === "passed") {
      return (
        "Added my own thinking and sent it (score " +
        scoreChange(step.score, next.score) +
        ")."
      );
    }
    if (next.action === "sent_anyway") return "Chose to send anyway.";
    return (
      "Revised and tried again (score " +
      scoreChange(step.score, next.score) +
      "), still held."
    );
  }

  /**
   * @param {object[]} entries  journal entries, oldest first
   * @param {object} [options]  { studentName, assignment, exportedAt, version, gapMinutes }
   */
  function buildReport(entries, options = {}) {
    const gapMs = (options.gapMinutes || DEFAULT_GAP_MINUTES) * 60 * 1000;
    const sorted = [...(entries || [])].sort((a, b) => a.time - b.time);

    // Group into sessions by time gap.
    const groups = [];
    for (const entry of sorted) {
      const last = groups[groups.length - 1];
      if (last && entry.time - last[last.length - 1].time <= gapMs)
        last.push(entry);
      else groups.push([entry]);
    }

    let recoveries = 0;
    let stepNumber = 0;
    const sessions = groups.map((group, index) => {
      const steps = group.map((entry, i) => {
        const next = group[i + 1] || null;
        if (entry.action === "held" && next && next.action === "passed")
          recoveries++;
        stepNumber++;
        return {
          n: stepNumber,
          time: entry.time,
          site: entry.site,
          action: entry.action,
          score: hasScore(entry.score) ? entry.score : null,
          threshold: hasScore(entry.threshold) ? entry.threshold : null,
          intent: entry.intent || "",
          effort: entry.effort || "",
          question: entry.question || "",
          attempt: entry.attempt || "",
          redWords: entry.redWords || [],
          advice: entry.advice || [],
          outcome: describeOutcome(entry, next),
        };
      });
      return {
        number: index + 1,
        start: group[0].time,
        end: group[group.length - 1].time,
        steps,
      };
    });

    const count = (action) => sorted.filter((e) => e.action === action).length;
    return {
      title: "XAI Learning Journal",
      studentName: options.studentName || "",
      assignment: options.assignment || "",
      exportedAt: options.exportedAt || Date.now(),
      version: options.version || "",
      summary: {
        total: sorted.length,
        sessions: sessions.length,
        passed: count("passed"),
        held: count("held"),
        sentAnyway: count("sent_anyway"),
        recoveries,
      },
      sessions,
      reflectionPrompts: REFLECTION_PROMPTS,
      caveat: CAVEAT,
    };
  }

  function defaultFormat(t) {
    return new Date(t).toLocaleString("en-US");
  }

  function actionTitle(step) {
    const s = hasScore(step.score) ? step.score : "?";
    const need = hasScore(step.threshold) ? step.threshold : "?";
    if (step.action === "passed") return "Sent (score " + s + ")";
    if (step.action === "held")
      return "Held (score " + s + ", needs " + need + ")";
    return "Sent anyway (score " + s + ", needs " + need + ")";
  }

  /** Quote user text so it can never be mistaken for report structure. */
  function quote(text) {
    const clean = String(text || "").trim();
    if (!clean) return "> _(nothing)_";
    return clean
      .split(/\r?\n/)
      .map((line) => "> " + line)
      .join("\n");
  }

  /** The report as Markdown text. */
  function toMarkdown(report, options = {}) {
    const fmt = options.formatTime || defaultFormat;
    const out = [];
    out.push("# " + report.title, "");
    if (report.studentName) out.push("- **Student:** " + report.studentName);
    if (report.assignment) out.push("- **Assignment:** " + report.assignment);
    out.push("- **Exported:** " + fmt(report.exportedAt));
    out.push(
      "- **Tool:** StudyGuard" + (report.version ? " v" + report.version : ""),
      ""
    );

    const s = report.summary;
    out.push("## Summary", "");
    out.push(
      "- Messages recorded: " +
        s.total +
        " across " +
        s.sessions +
        " session(s)"
    );
    out.push("- Sent without a hold: " + s.passed);
    out.push("- Held for more effort: " + s.held);
    out.push("- Chose to send anyway: " + s.sentAnyway);
    out.push("- Held, then revised and sent: " + s.recoveries, "");

    if (report.sessions.length === 0) {
      out.push("_No journal entries yet._", "");
    }

    for (const session of report.sessions) {
      out.push(
        "## Session " + session.number + " \u2013 " + fmt(session.start),
        ""
      );
      for (const step of session.steps) {
        out.push("### Step " + step.n + ": " + actionTitle(step), "");
        out.push(
          "_" + fmt(step.time) + (step.site ? " on " + step.site : "") + "_",
          ""
        );
        out.push("**What I asked**", "", quote(step.question), "");
        out.push("**My attempt**", "", quote(step.attempt), "");
        if (step.intent || step.effort) {
          out.push(
            "**How StudyGuard read it:** " +
              (step.intent || "unknown") +
              "; my visible effort: " +
              (step.effort || "unknown"),
            ""
          );
        }
        if (step.redWords.length) {
          out.push(
            "**Words that pushed the score toward needing more effort:** " +
              step.redWords.join(", "),
            ""
          );
        }
        if (step.advice.length) {
          out.push("**Advice shown:**", "");
          step.advice.forEach((a) => out.push("- " + a));
          out.push("");
        }
        out.push("**What happened next:** " + step.outcome, "");
      }
    }

    out.push("## My reflection", "");
    report.reflectionPrompts.forEach((p) =>
      out.push("**" + p + "**", "", "_(write your answer here)_", "")
    );
    out.push("---", "", "_" + report.caveat + "_", "");
    return out.join("\n");
  }

  const api = {
    buildReport,
    toMarkdown,
    describeOutcome,
    scoreChange,
    DEFAULT_GAP_MINUTES,
  };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else globalThis.StudyGuardJournalExport = api;
})();
